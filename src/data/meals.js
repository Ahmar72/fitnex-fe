export function mealsByCategory(category) {
  if (!category || category === 'all') return MEALS;
  return MEALS.filter((m) => m.category === category);
}

/** Returns the top N meals recommended for a given goal. */
export function recommendedMeals(goalKey, muscles = [], n = 4) {
  const byGoal = mealsByGoal(goalKey);
  if (!muscles.length) return byGoal.slice(0, n);
  // Prioritize meals that target the same muscles the user trained
  const scored = byGoal.map((m) => ({
    ...m,
    score: m.targetMuscles.filter((t) => muscles.includes(t)).length,
  }));
  return scored.sort((a, b) => b.score - a.score).slice(0, n);
}

export const getMealById = (id) => MEALS.find((m) => m.id === id) || null;
