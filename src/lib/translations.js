/**
 * Translates step instructions into the selected language
 */
export function translateSteps(steps, lang, i18nData = null) {
  if (!steps || !Array.isArray(steps)) return [];

  // If i18n has this language, use it directly!
  if (i18nData && i18nData[lang] && Array.isArray(i18nData[lang])) {
    return i18nData[lang];
  }

  // If Urdu is selected, apply Urdu translation rules
  if (lang === 'ur') {
    return steps.map((step) => {
      let text = String(step);
      for (const [pattern, translation] of URDU_PHRASES) {
        if (pattern.test(text)) {
          text = text.replace(pattern, translation);
        }
      }
      return text;
    });
  }

  // Fallback to English steps
  return steps;
}
